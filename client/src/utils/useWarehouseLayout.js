import { useEffect, useState } from 'react';
import { api } from './api';

/**
 * The warehouse layout, fetched once per session and shared by every consumer.
 *
 * Module-level cache rather than context: the pull list, the bench and the
 * editor all want the same immutable-ish blob, none of them wants to
 * re-render each other, and a layout changes about as often as furniture
 * moves. `refreshWarehouseLayout()` is the editor's save hook — it replaces
 * the cache and pokes every mounted subscriber.
 *
 * A store with no map (or a viewer whose role cannot read one) resolves to
 * null, and every consumer renders nothing — the map is a picture over bin
 * strings, never a dependency.
 */

let cached; // undefined = never fetched, null = fetched and absent
let inflight = null;
const subscribers = new Set();

async function fetchLayout() {
  if (!inflight) {
    inflight = api.get('/fulfilment/warehouse')
      .then((res) => { cached = res.layout || null; return cached; })
      .catch(() => { cached = null; return null; })
      .finally(() => { inflight = null; });
  }
  return inflight;
}

/** Replace the cache after a save, and tell every mounted consumer. */
export function refreshWarehouseLayout(layout) {
  cached = layout || null;
  for (const fn of subscribers) fn(cached);
}

export function useWarehouseLayout() {
  const [layout, setLayout] = useState(cached === undefined ? null : cached);

  useEffect(() => {
    const sub = (l) => setLayout(l);
    subscribers.add(sub);
    if (cached === undefined) fetchLayout().then(sub);
    else setLayout(cached);
    return () => subscribers.delete(sub);
  }, []);

  return layout;
}

/**
 * Which shelf a bin string belongs to: exact name or `NAME-…`, longest name
 * winning — the same rule the server's walk order applies, restated here only
 * because the chip highlights geometry the server never sends per-line.
 */
export function shelfForBin(layout, bin) {
  if (!layout || !bin) return null;
  const b = String(bin).toUpperCase();
  let best = null;
  for (const s of layout.shelves) {
    if (b === s.name || b.startsWith(`${s.name}-`)) {
      if (!best || s.name.length > best.name.length) best = s;
    }
  }
  return best;
}

/**
 * The level and slot a bin names, if it names them.
 *
 * Bins are generated by the slot grid as `SHELF-L<level>-S<slot>`, but a store
 * can also file a variant on a bare shelf ("A1") or under any other suffix it
 * likes — the canonical-bins rule means the layout is a picture over whatever
 * strings the store already uses, never a format it imposes. So this returns
 * nulls rather than guessing, and every caller draws the shelf and stops there
 * when it cannot tell which part of it to point at.
 *
 * Clamped to the shelf's declared geometry: a bin reading `A1-L9-S40` on a
 * two-level, six-slot shelf is a code from before somebody shrank the shelf,
 * and pointing at a section that is not there is worse than pointing at the
 * shelf. Out-of-range comes back null, which draws the whole shelf.
 */
export function parseBinSlot(shelf, bin) {
  if (!shelf || !bin) return { level: null, slot: null };
  const b = String(bin).toUpperCase();
  if (!b.startsWith(`${shelf.name}-`)) return { level: null, slot: null };

  const m = /-L(\d{1,3})(?:-S(\d{1,3}))?$/.exec(b);
  if (!m) return { level: null, slot: null };

  const levels = Math.max(1, Number(shelf.levels) || 1);
  const slots = Math.max(1, Number(shelf.slots_per_level) || 1);
  const level = Number(m[1]);
  const slot = m[2] === undefined ? null : Number(m[2]);

  return {
    level: Number.isInteger(level) && level >= 1 && level <= levels ? level : null,
    slot: slot !== null && Number.isInteger(slot) && slot >= 1 && slot <= slots ? slot : null,
  };
}

/**
 * The patch of floor one slot occupies, in grid units.
 *
 * Slots run along the shelf's LONG axis, because that is how a shelf works:
 * you walk its length and the sections go past you. Which axis that is comes
 * from the footprint the operator drew rather than from `rotation`, so a shelf
 * dragged from wide to tall keeps its sections running the right way with no
 * second property to keep in step.
 */
export function slotRect(shelf, slot) {
  const slots = Math.max(1, Number(shelf?.slots_per_level) || 1);
  if (!shelf || !Number.isInteger(slot) || slot < 1 || slot > slots) return null;
  const i = slot - 1;
  if (shelf.w >= shelf.h) {
    const step = shelf.w / slots;
    return { x: shelf.x + i * step, y: shelf.y, w: step, h: shelf.h };
  }
  const step = shelf.h / slots;
  return { x: shelf.x, y: shelf.y + i * step, w: shelf.w, h: step };
}

/**
 * One stop on a walk, resolved to the patch of floor somebody stands in front
 * of rather than to the whole run of shelving.
 *
 * Callers pass whatever their line carries — a bin (`A2-L4-S6`) or a bare
 * shelf name — and get back the shelf, the level and slot when the code names
 * them, the patch that slot occupies, and the point every marker for that stop
 * should hang off. Everything a map draws for a stop (its number, the path
 * through it, the lit patch) anchors on `at`, so the three cannot drift apart.
 *
 * This exists because anchoring on the shelf was the difference between "walk
 * to A2" and "walk to A2 and search eight feet of it" — the same reason the
 * section marker exists — and because a walk with two bins on one shelf
 * collapsed into a single number that pointed at neither of them.
 */
export function resolveStop(layout, code) {
  const shelf = shelfForBin(layout, code);
  if (!shelf) return null;
  const { level, slot } = parseBinSlot(shelf, code);
  // No slot in the code (a bare shelf name, or a bin from before somebody
  // shrank the shelf) means the honest anchor is the whole footprint.
  const patch = slotRect(shelf, slot) || {
    x: shelf.x, y: shelf.y, w: shelf.w, h: shelf.h,
  };
  return {
    shelf,
    bin: String(code).toUpperCase(),
    level,
    slot,
    patch,
    at: [patch.x + patch.w / 2, patch.y + patch.h / 2],
  };
}

/** Floors, oldest layouts included — one implicit floor when none are drawn. */
export function floorsOf(layout) {
  const list = Array.isArray(layout?.floors) ? layout.floors : [];
  return list.length > 0 ? list : [{ id: 'ground', name: 'Ground floor' }];
}

/**
 * Only what stands on one floor.
 *
 * Returns the layout unchanged for a single-floor store, so the common case
 * allocates nothing and every consumer can call this unconditionally.
 */
export function floorSlice(layout, floorId) {
  if (!layout) return null;
  const floors = floorsOf(layout);
  if (floors.length <= 1) return layout;
  const id = floors.some((f) => f.id === floorId) ? floorId : floors[0].id;
  const on = (o) => (o.floor_id || floors[0].id) === id;
  return { ...layout, rooms: layout.rooms.filter(on), shelves: layout.shelves.filter(on) };
}
